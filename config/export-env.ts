/**
 * Export a network's addresses as environment variable lines.
 *
 * `networks.ts` stays the only source of an address. A Forge test cannot read
 * TypeScript, so it reads `vm.envAddress`. This script fills that gap. It
 * imports `networks.ts` rather than parsing it, so the two cannot drift.
 *
 * Usage:
 *   bun config/export-env.ts 11155111            print the lines
 *   bun config/export-env.ts 11155111 >> .env    load them for forge
 *
 * Every key is prefixed `AR_` so these never collide with an operator secret.
 * Contract keys keep their `networks.ts` name, upper snake cased. Token keys
 * take an extra `TOKEN_`.
 *
 * This writes no file of its own. `addresses.json` was removed on purpose, so
 * do not reintroduce a second address file. See STATE.md.
 */
import { getNetwork } from "./networks.js";

function toKey(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
}

const chainId = Number(process.argv[2]);
if (!Number.isFinite(chainId)) {
  console.error("usage: bun config/export-env.ts <chainId>");
  process.exit(1);
}

const net = getNetwork(chainId);
const lines: string[] = [
  `# Addresses for ${net.name}, chain id ${net.chainId}.`,
  `# Generated by config/export-env.ts from config/networks.ts.`,
  `# Source: ${net.source.branch} at ${net.source.commit}, deployed ${net.source.deployedAt}.`,
  `# Do not edit by hand. Re-run the script instead.`,
  `AR_CHAIN_ID=${net.chainId}`,
];

for (const [name, addr] of Object.entries(net.addresses)) {
  lines.push(`AR_${toKey(name)}=${addr}`);
}
for (const [name, addr] of Object.entries(net.tokens)) {
  lines.push(`AR_TOKEN_${toKey(name)}=${addr}`);
}

console.log(lines.join("\n"));
